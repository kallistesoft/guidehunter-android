package ca.kallistesoft.guidehunter.core.designsystem.theme

import androidx.compose.ui.unit.dp

/** Spacing scale used by every screen, so gaps stay consistent. The only place gaps are given in dp. */
object Spacing {
    val none = 0.dp
    val xxs = 2.dp
    val xs = 4.dp
    val s = 8.dp
    val m = 12.dp
    val l = 16.dp
    val xl = 20.dp
    val xxl = 24.dp
    val xxxl = 32.dp

    /** Side margin of a screen's content. */
    val screen = xl
}
