import kotlinx.kover.gradle.plugin.dsl.CoverageUnit
import kotlinx.kover.gradle.plugin.dsl.GroupingEntityType
import kotlinx.kover.gradle.plugin.dsl.KoverProjectExtension
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.kotlin.dsl.configure

/**
 * Unit test coverage with Kover. Each module gets a `unit` report variant (the debug unit tests of an Android module,
 * the tests of a JVM module); the root project merges them. `./gradlew koverVerifyUnit` fails when any class has
 * less than [MIN_LINE_COVERAGE]% of its lines covered; `./gradlew koverHtmlReportUnit` writes
 * build/reports/kover/htmlUnit, which shows the missed lines.
 */
class KoverConventionPlugin : Plugin<Project> {
    override fun apply(target: Project) {
        with(target) {
            pluginManager.apply("org.jetbrains.kotlinx.kover")
            extensions.configure<KoverProjectExtension> {
                currentProject {
                    createVariant(VARIANT) { add("debug", "jvm", optional = true) }
                }
                reports {
                    filters.excludes {
                        // Code generated by Hilt, Dagger, Compose and AGP: nothing of ours to test.
                        classes(
                            "*.BuildConfig",
                            "*ComposableSingletons*",
                            "*Hilt_*",
                            "*HiltWrapper_*",
                            "*Factory\$InstanceHolder",
                            "*_Factory",
                            "*_Factory\$*",
                            "*_HiltModules*",
                            "*_MembersInjector",
                            "*_GeneratedInjector",
                            "*_ComponentTreeDeps",
                            "*_Provide*Factory*",
                            "dagger.hilt.internal.aggregatedroot.codegen.*",
                            "hilt_aggregated_deps.*",
                        )
                        // Previews only feed Android Studio and the screenshot tests.
                        annotatedBy("androidx.compose.ui.tooling.preview.Preview", "*Generated*")
                    }
                    // On the merged report only: a class may be covered by another module's tests.
                    if (this@with == rootProject) verify.rule("Every class") {
                        groupBy.set(GroupingEntityType.CLASS)
                        bound {
                            minValue.set(MIN_LINE_COVERAGE)
                            coverageUnits.set(CoverageUnit.LINE)
                        }
                    }
                }
            }
        }
    }

    private companion object {
        const val VARIANT = "unit"
        const val MIN_LINE_COVERAGE = 90
    }
}
