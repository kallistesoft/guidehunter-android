"""
GuideHunter's logo, B ("the pin"): the map pin with a crossed rifle and fishing rod in its head. One geometry, written
as the app's launcher icon drawables and as an SVG preview (design/mockup/Logo.dc.html shows the same).

    python3 design/generator/logo.py app/src/main/res/drawable build/logo-preview.html

The crossing is drawn bold (thick barrel and rod, no scope mounts, no line detail) so it holds at 48 px; the themed
icon (one colour) puts it in a round window cut in the pin's head.
"""
import sys

PIN = "M54,24C42.4,24 33,33.4 33,45C33,60 54,84 54,84C54,84 75,60 75,45C75,33.4 65.6,24 54,24Z"
HOLE = "M39,45a15,15 0,1 0,30 0a15,15 0,1 0,-30 0Z"  # themed icon: the window in the pin's head

def rrect(x, y, w, h, r):
    r = min(r, w / 2, h / 2)
    return (f"M{x+r:g},{y:g}H{x+w-r:g}A{r:g},{r:g} 0,0 1,{x+w:g},{y+r:g}V{y+h-r:g}"
            f"A{r:g},{r:g} 0,0 1,{x+w-r:g},{y+h:g}H{x+r:g}A{r:g},{r:g} 0,0 1,{x:g},{y+h-r:g}"
            f"V{y+r:g}A{r:g},{r:g} 0,0 1,{x+r:g},{y:g}Z")

def circle(cx, cy, r):
    return f"M{cx-r:g},{cy:g}a{r:g},{r:g} 0,1 0,{2*r:g},0a{r:g},{r:g} 0,1 0,{-2*r:g},0Z"

# Drawn horizontally on the 108 grid, centred on (54, 54); the rifle turns -45°, the rod +45°.
RIFLE_FILL = ["M12,50L30,48.5L38,51.5L38,58L30,59L12,62Z", rrect(36, 50, 21, 7, 2), rrect(40, 44.5, 14, 4.2, 2),
              rrect(55, 51, 40, 4.5, 2)]
ROD_FILL = [rrect(70, 50.5, 26, 7.5, 3.7), circle(66, 62, 5.5), "M72,51.5L12,53L12,55.5L72,57Z"]
ROD_LINE = "M12,54C9,63 13,69 18,71"

FULL = dict(scale=0.42, pivot_dy=-9)   # the crossing in the pin's head (centre 54, 45)
THEMED = dict(scale=0.30, pivot_dy=-9)

def vector(pin_color, glyph_color, mode, comment):
    s = THEMED if mode == "themed" else FULL
    pin = (f'''    <path
        android:fillColor="{pin_color}"
        android:fillType="evenOdd"
        android:pathData="{PIN}{HOLE}" />''' if mode == "themed" else f'''    <path
        android:fillColor="{pin_color}"
        android:pathData="{PIN}" />''')
    def paths(fills, color, line=None):
        out = "".join(f'''
            <path
                android:fillColor="{color}"
                android:pathData="{d}" />''' for d in fills)
        if line:
            out += f'''
            <path
                android:pathData="{line}"
                android:strokeWidth="2.4"
                android:strokeColor="{color}"
                android:strokeLineCap="round" />'''
        return out
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Generated by design/generator/logo.py: edit there, not by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{pin}
    <!-- The crossing: drawn horizontally, centred on (54, 54), then turned and scaled into the pin's head. -->
    <group
        android:pivotX="54"
        android:pivotY="54"
        android:scaleX="{s['scale']}"
        android:scaleY="{s['scale']}"
        android:translateY="{s['pivot_dy']}">
        <group
            android:pivotX="54"
            android:pivotY="54"
            android:rotation="-45">{paths(RIFLE_FILL, glyph_color)}
        </group>
        <group
            android:pivotX="54"
            android:pivotY="54"
            android:rotation="45">{paths(ROD_FILL, glyph_color, ROD_LINE)}
        </group>
    </group>
</vector>
'''

def svg_icon(size, bg, pin_color, glyph_color, mode):
    s = THEMED if mode == "themed" else FULL
    pin_d = PIN + (HOLE if mode == "themed" else "")
    def g(fills, color, rot, line=None):
        inner = "".join(f'<path d="{d}" fill="{color}"/>' for d in fills)
        if line:
            inner += f'<path d="{line}" fill="none" stroke="{color}" stroke-width="2.4" stroke-linecap="round"/>'
        return f'<g transform="rotate({rot} 54 54)">{inner}</g>'
    # Same transform as the vector's group: scale around (54,54), then move up by pivot_dy.
    t = f'translate(0 {s["pivot_dy"]}) translate(54 54) scale({s["scale"]}) translate(-54 -54)'
    return (f'<svg width="{size}" height="{size}" viewBox="18 18 72 72"><circle cx="54" cy="54" r="36" fill="{bg}"/>'
            f'<path d="{pin_d}" fill="{pin_color}" fill-rule="evenodd"/><g transform="{t}">'
            f'{g(RIFLE_FILL, glyph_color, -45)}{g(ROD_FILL, glyph_color, 45, ROD_LINE)}</g></svg>')

if __name__ == "__main__":
    res = sys.argv[1]
    open(f"{res}/ic_launcher_foreground.xml", "w").write(vector("#F27B2B", "#17331F", "full",
        "App icon and splash icon foreground: logo B, the map pin in blaze orange with a crossed rifle and fishing rod "
        "in its head, in deep green (design/mockup/Logo.dc.html). Drawn on the adaptive icon's 108 grid, inside the "
        "66 dp safe zone."))
    open(f"{res}/ic_launcher_monochrome.xml", "w").write(vector("#FFFFFFFF", "#FFFFFFFF", "themed",
        "Themed icon (Android 13+): logo B in one colour. The crossing can't be dark on the pin in one colour, so it "
        "sits in a round window cut in the pin's head."))
    rows = [svg_icon(192, "#1F4229", "#F27B2B", "#17331F", "full"), svg_icon(96, "#1F4229", "#F27B2B", "#17331F", "full"),
            svg_icon(48, "#1F4229", "#F27B2B", "#17331F", "full"),
            svg_icon(48, "#E3EFE4", "#2F6B3E", "#2F6B3E", "themed"), svg_icon(48, "#22382A", "#8FD19E", "#8FD19E", "themed")]
    open(sys.argv[2], "w").write('<!doctype html><html><body style="margin:0;background:#0E1611;display:flex;gap:24px;'
                                 'align-items:flex-end;padding:20px">' + "".join(rows) + "</body></html>")
